# 3. สร้างโฟลเดอร์หลัก
# ------------------------------------------------------------

New-Item `
    -ItemType Directory `
    -Path $Root `
    -Force |
    Out-Null

foreach ($Directory in $Directories) {
    $FullPath = Join-Path $Root $Directory

    New-Item `
        -ItemType Directory `
        -Path $FullPath `
        -Force |
        Out-Null
}

# ------------------------------------------------------------
# 4. สร้างไฟล์ Markdown พร้อมหัวข้อเริ่มต้น
#    จะไม่เขียนทับไฟล์ที่มีอยู่แล้ว
# ------------------------------------------------------------

foreach ($RelativePath in $MarkdownFiles) {
    $FullPath = Join-Path $Root $RelativePath

    if (-not (Test-Path -LiteralPath $FullPath)) {
        $FileName = [System.IO.Path]::GetFileNameWithoutExtension($FullPath)
        $Title = $FileName.Replace("_", " ")

        $Content = @"
---
schema_version: 4.0
updated: $(Get-Date -Format "yyyy-MM-dd")
---

# STGB — $Title

"@

        Set-Content `
            -LiteralPath $FullPath `
            -Value $Content `
            -Encoding UTF8
    }
}

